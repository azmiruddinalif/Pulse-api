export function generateMarkdownDocs(collection: any): string {
  const lines: string[] = [];

  lines.push('# ' + (collection.name || 'API Documentation'));
  if (collection.description) {
    lines.push('\n' + collection.description + '\n');
  }
  lines.push('\n*Generated by Pulse API Client on ' + new Date().toLocaleDateString() + '*\n');

  function processFolder(folder: any, depth: number = 2) {
    const heading = '#'.repeat(depth);
    lines.push('\n' + heading + ' ' + folder.name + '\n');
    if (folder.description) lines.push(folder.description + '\n');

    if (folder.requests && folder.requests.length > 0) {
      for (const req of folder.requests) {
        lines.push('\n' + '#'.repeat(depth + 1) + ' ' + (req.name || req.url));
        lines.push('```http\n' + req.method + ' ' + req.url + '\n```\n');
        if (req.description) lines.push(req.description + '\n');

        const activeHeaders = (req.headers || []).filter((h: any) => h.enabled && h.key);
        if (activeHeaders.length > 0) {
          lines.push('**Headers:**\n');
          lines.push('| Header | Value |');
          lines.push('| --- | --- |');
          for (const h of activeHeaders) {
            lines.push('| `' + h.key + '` | `' + h.value + '` |');
          }
          lines.push('');
        }

        const activeParams = (req.params || []).filter((p: any) => p.enabled && p.key);
        if (activeParams.length > 0) {
          lines.push('**Query Parameters:**\n');
          lines.push('| Parameter | Value | Description |');
          lines.push('| --- | --- | --- |');
          for (const p of activeParams) {
            lines.push('| `' + p.key + '` | `' + p.value + '` | ' + (p.description || '-') + ' |');
          }
          lines.push('');
        }

        if (req.body && req.bodyType !== 'none') {
          lines.push('**Request Body (' + req.bodyType + '):**\n');
          lines.push('```json\n' + req.body + '\n```\n');
        }
      }
    }

    if (folder.folders && folder.folders.length > 0) {
      for (const sub of folder.folders) {
        processFolder(sub, depth + 1);
      }
    }
  }

  processFolder(collection, 2);
  return lines.join('\n');
}

export function generateHtmlDocs(collection: any): string {
  const md = generateMarkdownDocs(collection);
  return '<!DOCTYPE html>\n' +
    '<html lang="en">\n' +
    '<head>\n' +
    '  <meta charset="UTF-8">\n' +
    '  <title>' + (collection.name || 'API Documentation') + '</title>\n' +
    '  <style>body{font-family:sans-serif;background:#0c1017;color:#cbd5e1;padding:40px;}pre{background:#131823;padding:20px;border-radius:8px;}</style>\n' +
    '</head>\n' +
    '<body>\n' +
    '  <pre>' + md.replace(/</g, '&lt;').replace(/>/g, '&gt;') + '</pre>\n' +
    '</body>\n' +
    '</html>';
}