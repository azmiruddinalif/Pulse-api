export function generateOpenApiSpec(collection: any): string {
  const paths: Record<string, any> = {};

  function cleanPath(rawUrl: string): string {
    try {
      const parsed = new URL(rawUrl.startsWith('http') ? rawUrl : 'https://' + rawUrl);
      return parsed.pathname || '/';
    } catch {
      const match = rawUrl.match(/https?:\/\/[^/]+(\/.+)/);
      return match ? match[1] : (rawUrl.startsWith('/') ? rawUrl : '/' + rawUrl);
    }
  }

  const allRequests = [
    ...(collection.requests || []),
    ...(collection.folders || []).flatMap((f: any) => f.requests || [])
  ];

  for (const req of allRequests) {
    const pathKey = cleanPath(req.url);
    if (!paths[pathKey]) paths[pathKey] = {};

    const methodKey = (req.method || 'GET').toLowerCase();
    const parameters = (req.params || []).filter((p: any) => p.enabled && p.key).map((p: any) => ({
      name: p.key,
      in: 'query',
      description: p.description || '',
      required: false,
      schema: { type: 'string', example: p.value }
    }));

    let requestBody: any = undefined;
    if (req.body && req.bodyType === 'json') {
      try {
        const parsed = JSON.parse(req.body);
        requestBody = {
          required: true,
          content: {
            'application/json': {
              schema: { type: 'object', example: parsed }
            }
          }
        };
      } catch {
        requestBody = {
          required: true,
          content: {
            'application/json': {
              schema: { type: 'string', example: req.body }
            }
          }
        };
      }
    }

    paths[pathKey][methodKey] = {
      summary: req.name || (req.method + ' ' + pathKey),
      description: req.description || 'Generated by Pulse API Client',
      parameters: parameters.length ? parameters : undefined,
      requestBody,
      responses: {
        '200': {
          description: 'Successful response',
          content: {
            'application/json': {
              schema: { type: 'object' }
            }
          }
        }
      }
    };
  }

  const spec = {
    openapi: '3.0.3',
    info: {
      title: collection.name || 'API Specification',
      description: collection.description || 'Exported from Pulse Desktop Client',
      version: '1.0.0',
    },
    paths,
  };

  return JSON.stringify(spec, null, 2);
}