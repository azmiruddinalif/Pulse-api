import React, { useState } from 'react';
import { BookOpen, Download, X, Copy, Check } from 'lucide-react';
import { useStore } from '../../store/useStore';

export const DocPreviewModal: React.FC = () => {
  const { isDocModalOpen, setIsDocModalOpen, docCollection } = useStore();
  const [copied, setCopied] = useState(false);

  if (!isDocModalOpen || !docCollection) return null;

  const generateMarkdown = () => {
    let md = '# ' + docCollection.name + '\n\n';
    if (docCollection.description) md += docCollection.description + '\n\n';
    md += '*Generated by Pulse API Client on ' + new Date().toLocaleDateString() + '*\n\n---\n\n';

    const allRequests = [
      ...docCollection.requests,
      ...docCollection.folders.flatMap(f => f.requests)
    ];

    allRequests.forEach((req, i) => {
      md += '### ' + (i + 1) + '. ' + req.name + '\n\n';
      md += '```http\n' + req.method + ' ' + req.url + '\n```\n\n';
      if (req.headers && req.headers.length) {
        md += '**Headers:**\n';
        req.headers.filter(h => h.enabled).forEach(h => {
          md += '- `' + h.key + '`: `' + h.value + '`\n';
        });
        md += '\n';
      }
      if (req.body && req.bodyType !== 'none') {
        md += '**Body (' + req.bodyType + '):**\n```json\n' + req.body + '\n```\n\n';
      }
    });

    return md;
  };

  const mdContent = generateMarkdown();

  const handleCopy = () => {
    navigator.clipboard.writeText(mdContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = (ext: 'md' | 'html') => {
    const filename = docCollection.name.toLowerCase().replace(/\s+/g, '-') + '-docs.' + ext;
    const content = ext === 'html'
      ? '<!DOCTYPE html><html><head><meta charset="utf-8"><title>' + docCollection.name + '</title><style>body{font-family:sans-serif;background:#0d111a;color:#e2e8f0;padding:40px;max-width:800px;margin:auto;}pre{background:#161c2e;padding:12px;border-radius:6px;}</style></head><body><pre>' + mdContent.replace(/</g, '&lt;') + '</pre></body></html>'
      : mdContent;

    if (window.pulseAPI?.exportToFile) {
      window.pulseAPI.exportToFile(filename, content, ext.toUpperCase() + ' Documentation', [ext]);
    } else {
      const blob = new Blob([content], { type: 'text/plain' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = filename;
      a.click();
      URL.revokeObjectURL(url);
    }
  };

  return (
    <div className="fixed inset-0 bg-black/70 backdrop-blur-sm flex items-center justify-center p-4 z-50">
      <div className="w-full max-w-3xl bg-pulse-card border border-pulse-border rounded-xl shadow-2xl overflow-hidden flex flex-col max-h-[85vh]">
        <div className="px-5 py-4 border-b border-pulse-border flex items-center justify-between bg-[#111624]">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-pink-500/15 border border-pink-500/30 flex items-center justify-center">
              <BookOpen className="w-4 h-4 text-pink-400" />
            </div>
            <div>
              <h3 className="text-sm font-semibold text-slate-100">API Documentation</h3>
              <p className="text-[11px] text-slate-400">{docCollection.name}</p>
            </div>
          </div>
          <button
            onClick={() => setIsDocModalOpen(false)}
            className="text-slate-400 hover:text-slate-200 p-1 rounded-md hover:bg-pulse-hover"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        <div className="p-4 bg-[#090d16] flex items-center justify-between border-b border-pulse-border">
          <span className="text-xs text-slate-400">Format: Markdown / HTML</span>
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1 px-3 py-1.5 rounded-md bg-pulse-panel hover:bg-pulse-hover border border-pulse-border text-xs text-slate-300"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={() => handleDownload('md')}
              className="flex items-center gap-1 px-3 py-1.5 rounded-md bg-blue-600 hover:bg-blue-500 text-xs text-white"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download Markdown</span>
            </button>
            <button
              onClick={() => handleDownload('html')}
              className="flex items-center gap-1 px-3 py-1.5 rounded-md bg-pink-600 hover:bg-pink-500 text-xs text-white"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download HTML</span>
            </button>
          </div>
        </div>

        <div className="p-5 flex-1 overflow-y-auto bg-[#090d16]">
          <pre className="text-xs font-mono text-slate-200 whitespace-pre-wrap leading-relaxed">
            {mdContent}
          </pre>
        </div>
      </div>
    </div>
  );
};